#!/usr/bin/env python3
"""Write the per-brief expert reference (validation layer 1) to ``references/``.

For each brief, from its hidden forces and the expert impact ratings (``inputs/gt_model.json``):

- relevant decisions: the expert decisions whose options differ in their summed impact on the brief's forces;
- preferred options: per relevant decision, the options with the best sum.

``score.py`` computes the same reference (``score.relevant_decisions``) for relevant-decision coverage; these
files are its readable, reviewable form. Write them once the briefs are final and before any session runs.

The briefs are checked first (known force ids, each with an impact on some expert decision).

Usage::

    python study/cain2027/reference.py            # check the briefs and write the references
    python study/cain2027/reference.py --forces   # list the force ids a brief can use
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Mapping

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import design  # noqa: E402
import score  # noqa: E402

HERE = Path(__file__).resolve().parent
REFERENCES = HERE / "references"


def reference(gt: Mapping[str, Any], brief: Mapping[str, Any]) -> Dict[str, Any]:
    """Return the brief's reference: its forces, and its relevant decisions with options ranked by summed impact."""
    names = {x["id"]: x.get("name") or x["id"] for key in ("decisions", "options", "forces") for x in gt.get(key) or []}
    impacts: Dict[str, List[str]] = {}
    for i in gt.get("impacts") or []:
        if i["force_id"] in brief["forces"]:
            impacts.setdefault(i["option_id"], []).append(f"{names.get(i['force_id'], i['force_id'])} {i['impact']}")
    decisions = []
    for d, ref in score.relevant_decisions(gt, brief["forces"]).items():
        options = [{"id": o, "name": names.get(o, o), "sum": s, "preferred": o in ref["preferred"],
                    "impacts": sorted(impacts.get(o, []))}
                   for o, s in sorted(ref["sums"].items(), key=lambda kv: (-kv[1], names.get(kv[0], kv[0])))]
        decisions.append({"id": d, "name": names.get(d, d), "options": options})
    decisions.sort(key=lambda d: d["name"].lower())
    return {"brief": brief["id"], "system": brief.get("system"),
            "forces": [{"id": f, "name": names.get(f, f)} for f in brief["forces"]],
            "relevant_decisions": decisions, "expert_decisions": len(gt.get("decisions") or [])}


def render(ref: Mapping[str, Any], draft: bool) -> str:
    """Return the reference as Markdown."""
    lines = [f"# Expert reference: {ref['system']} (`{ref['brief']}`)", ""]
    if draft:
        lines += ["> DRAFT: `briefs.yaml` is still marked as a draft; regenerate once the briefs are final.", ""]
    lines += ["Generated by `reference.py` from `inputs/gt_model.json` and the brief's hidden forces. A yardstick,",
              "not the answer: the expert impacts were not rated for this brief.", "",
              "Forces: " + ", ".join(f"{f['name']} (`{f['id']}`)" for f in ref["forces"]) + ".", "",
              f"Relevant decisions: {len(ref['relevant_decisions'])} of {ref['expert_decisions']}. "
              "Options are ranked by summed impact on the forces (++ = 2 ... -- = -2, missing = 0); "
              "preferred options are in bold.", ""]
    for d in ref["relevant_decisions"]:
        lines += [f"## {d['name']}", "", "| Option | Sum | Impacts on the brief's forces |", "|---|---:|---|"]
        for o in d["options"]:
            name = f"**{o['name']}**" if o["preferred"] else o["name"]
            lines.append(f"| {name} | {o['sum']:+d} | {'; '.join(o['impacts']) or '-'} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    """Write ``references/<brief>.md`` and ``references/references.json`` (or, with ``--forces``, list the forces)."""
    gt = json.loads((design.INPUTS / "gt_model.json").read_text(encoding="utf-8"))
    if "--forces" in sys.argv[1:]:
        for f in sorted(gt.get("forces") or [], key=lambda f: f["id"]):
            print(f"{f['id']:40} {f.get('name') or ''}")  # noqa: T201
        return
    briefs = design.load_briefs()
    score.check_briefs(briefs, gt)
    draft = bool((yaml.safe_load(design.BRIEFS.read_text(encoding="utf-8")) or {}).get("draft"))
    REFERENCES.mkdir(exist_ok=True)
    refs = [reference(gt, b) for b in briefs]
    for ref in refs:
        (REFERENCES / f"{ref['brief']}.md").write_text(render(ref, draft), encoding="utf-8")
        print(f"{ref['brief']}: {len(ref['relevant_decisions'])} relevant decisions")  # noqa: T201
    (REFERENCES / "references.json").write_text(json.dumps(
        {"draft": draft, "briefs_sha256": design.sha256(design.BRIEFS),
         "gt_model_sha256": design.sha256(design.INPUTS / "gt_model.json"), "references": refs}, indent=2) + "\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
